// 単体テスト：ymd（テスト名に使う日付）
// テスト一覧の名前は「学習項目名-20261123」の形。月・日が1けたでも0を付けて8けたにする
import { describe, expect, it } from "vitest";
import { ymd } from "../../src/lib/logic";

describe("ymd：テスト名の日付", () => {
  it("年月日を8けたにする", () => expect(ymd("2026-11-23T12:00:00")).toBe("20261123"));
  it("1けたの月・日には0を付ける", () => expect(ymd("2026-01-05T09:00:00")).toBe("20260105"));
  it("時刻は名前に入れない", () => expect(ymd("2026-12-31T23:59:59")).toBe("20261231"));
});
